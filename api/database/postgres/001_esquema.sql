-- Buscador en PostgreSQL: estructura de tablas (sin datos). Equivale a la base Buscador de SQL Server.
-- Requisito: la base debe crearse con UTF8 y LC_CTYPE en_US.utf8 (citext y lower() dependen de ella):
--   CREATE DATABASE buscador ENCODING 'UTF8' LC_COLLATE 'en_US.utf8' LC_CTYPE 'en_US.utf8' TEMPLATE template0;
-- Es seguro ejecutarlo mas de una vez. Los indices de las 5 tablas grandes van aparte (002), despues de cargar los datos.
--
-- Equivalencias con SQL Server: varchar/nvarchar -> varchar (o citext donde se busca sin distinguir mayusculas,
-- como hacia Modern_Spanish_CI_AS), char(n) -> varchar(n), datetime -> timestamp(3), datetime2 -> timestamp(6),
-- bit -> boolean, tinyint -> smallint, decimal -> numeric, IDENTITY -> GENERATED BY DEFAULT AS IDENTITY.

CREATE EXTENSION IF NOT EXISTS citext;
CREATE SCHEMA IF NOT EXISTS rrcc;
CREATE SCHEMA IF NOT EXISTS operador;

-- ===================================================================================================
-- Aplicacion (esquema rrcc)
-- ===================================================================================================

CREATE TABLE IF NOT EXISTS rrcc.usuarios (
    cod_usuario  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres      citext       NOT NULL,
    ape_pat      citext       NOT NULL,
    ape_mat      citext,
    usuario      citext       NOT NULL,
    clave        varchar(255) NOT NULL,
    correo       citext,
    departamento varchar(150),
    provincia    varchar(150),
    distrito     varchar(150),
    direccion    varchar(150),
    telefono     varchar(150),
    dni          varchar(150),
    foto         varchar(150),
    estado       integer,
    usu_creo     varchar(20),
    fecha_creo   timestamp(3),
    usu_actu     varchar(20),
    fecha_actu   timestamp(3)
);

CREATE TABLE IF NOT EXISTS rrcc.roles (
    cod_rol     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_rol     citext       NOT NULL,
    descripcion varchar(250),
    estado      integer,
    usu_creo    varchar(20),
    fecha_creo  timestamp(3),
    usu_actu    varchar(20),
    fecha_actu  timestamp(3)
);

CREATE TABLE IF NOT EXISTS rrcc.menus (
    cod_menu       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_menu_padre integer,
    nom_menu       varchar(100) NOT NULL,
    ruta           varchar(200) NOT NULL,
    icono          varchar(100),
    orden          integer,
    estado         integer,
    usu_creo       varchar(20),
    fecha_creo     timestamp(3),
    usu_actu       varchar(20),
    fecha_actu     timestamp(3)
);

CREATE TABLE IF NOT EXISTS rrcc.rolmenu (
    cod_rol_menu   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_rol        integer NOT NULL REFERENCES rrcc.roles (cod_rol),
    cod_menu       integer NOT NULL REFERENCES rrcc.menus (cod_menu),
    puede_ver      integer,
    puede_crear    integer,
    puede_editar   integer,
    puede_eliminar integer,
    estado         integer,
    usu_creo       varchar(20),
    fecha_creo     timestamp(3),
    usu_actu       varchar(20),
    fecha_actu     timestamp(3),
    CONSTRAINT uq_rolmenu UNIQUE (cod_rol, cod_menu)
);

CREATE TABLE IF NOT EXISTS rrcc.usuariorol (
    cod_usuario_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usuario     integer NOT NULL REFERENCES rrcc.usuarios (cod_usuario),
    cod_rol         integer NOT NULL REFERENCES rrcc.roles (cod_rol),
    estado          integer,
    usu_creo        varchar(20),
    fecha_creo      timestamp(3),
    usu_actu        varchar(20),
    fecha_actu      timestamp(3),
    CONSTRAINT uq_usuariorol UNIQUE (cod_usuario, cod_rol)
);

-- Tokens de recuperacion de clave e invitacion de usuarios nuevos (tipo: 1 recuperacion, 2 invitacion)
CREATE TABLE IF NOT EXISTS rrcc.passwordresettokens (
    cod_token    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usuario  integer     NOT NULL REFERENCES rrcc.usuarios (cod_usuario),
    token_hash   varchar(64) NOT NULL,
    tipo         smallint    NOT NULL DEFAULT 1,
    fecha_creo   timestamp(6) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    fecha_expira timestamp(6) NOT NULL,
    usado        boolean     NOT NULL DEFAULT false,
    fecha_uso    timestamp(6),
    ip_solicitud varchar(45)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_prt_token_hash ON rrcc.passwordresettokens (token_hash);
CREATE INDEX IF NOT EXISTS ix_prt_usuario ON rrcc.passwordresettokens (cod_usuario, usado);

-- Saldo de tokens por usuario (ADMIN GENERAL es ilimitado y no usa esta tabla)
CREATE TABLE IF NOT EXISTS rrcc.tokensaldo (
    cod_usuario integer      PRIMARY KEY REFERENCES rrcc.usuarios (cod_usuario),
    saldo       integer      NOT NULL DEFAULT 0 CONSTRAINT ck_tokensaldo_nonegativo CHECK (saldo >= 0),
    fecha_actu  timestamp(6) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- Libro de movimientos de tokens: asignaciones, consumos, devoluciones y ajustes
CREATE TABLE IF NOT EXISTS rrcc.tokenmovimientos (
    cod_movimiento     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usuario        integer      NOT NULL REFERENCES rrcc.usuarios (cod_usuario),
    tipo               smallint     NOT NULL,   -- 1 asignacion, 2 consumo, 3 devolucion, 4 ajuste/retiro
    cantidad           integer      NOT NULL,   -- positivo suma, negativo resta
    saldo_resultante   integer      NOT NULL,
    accion             varchar(50)  NOT NULL,
    detalle            varchar(600),
    cod_usuario_accion integer,
    fecha              timestamp(6) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_tokenmov_usuario ON rrcc.tokenmovimientos (cod_usuario, cod_movimiento DESC);

-- Bitacora de auditoria (fechas en UTC)
CREATE TABLE IF NOT EXISTS rrcc.auditoria (
    cod_auditoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         timestamp(6) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    cod_usuario   integer,
    usuario       citext       NOT NULL,
    accion        citext       NOT NULL,
    entidad       varchar(60),
    entidad_id    varchar(60),
    detalle       varchar(1000),
    ip            varchar(45),
    exito         boolean      NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS ix_auditoria_fecha   ON rrcc.auditoria (fecha DESC);
CREATE INDEX IF NOT EXISTS ix_auditoria_usuario ON rrcc.auditoria (usuario, fecha DESC);
CREATE INDEX IF NOT EXISTS ix_auditoria_accion  ON rrcc.auditoria (accion, fecha DESC);

-- Revocacion de sesiones: todo token emitido antes de fecha_revocacion deja de ser valido para ese usuario
CREATE TABLE IF NOT EXISTS rrcc.sesionesrevocadas (
    cod_usuario      integer      PRIMARY KEY REFERENCES rrcc.usuarios (cod_usuario),
    fecha_revocacion timestamp(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS rrcc.historialdescarga (
    cod_historial  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usuario    integer      NOT NULL,
    nombre_archivo varchar(400) NOT NULL,
    ruta_archivo   varchar(800) NOT NULL,
    secciones      varchar(400) NOT NULL,
    total_dnis     integer      NOT NULL,
    tamano_bytes   bigint       NOT NULL,
    fecha_creo     timestamp(6) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_historialdescarga_usuario ON rrcc.historialdescarga (cod_usuario, fecha_creo DESC);

CREATE TABLE IF NOT EXISTS rrcc.logaccesos (
    cod_log      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usuario  integer     NOT NULL,
    ip           varchar(70) NOT NULL,
    fecha_acceso timestamp(3)
);

-- ===================================================================================================
-- Datos de consulta (5 tablas grandes, solo lectura para la aplicacion). Sus indices estan en 002.
-- documento es citext: la comparacion no distingue mayusculas, como en SQL Server.
-- ===================================================================================================

CREATE TABLE IF NOT EXISTS rrcc.deuda (
    periodo       varchar(6),
    codigosbs     varchar(10),
    documento     citext,
    razonsocial   varchar(150),
    codigoempresa varchar(5),
    entidad       varchar(100),
    tipo_deuda    varchar(30),
    dias          integer,
    calificacion  varchar(3),
    saldo         numeric(20,2),
    fecha_carga   timestamp(3) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rrcc.calificacion (
    periodo     varchar(6),
    codigosbs   varchar(10),
    documento   citext,
    nor         numeric(18,2),
    cpp         numeric(18,2),
    def         numeric(18,2),
    dud         numeric(18,2),
    per         numeric(18,2),
    reportan    varchar(4),
    ape_pat     varchar(250),
    ape_mat     varchar(60),
    pri_nombre  varchar(150),
    seg_nombre  varchar(150),
    fecha_carga timestamp(3) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rrcc.lineascredito (
    periodo            varchar(6),
    codigosbs          varchar(10),
    documento          citext,
    razonsocial        varchar(150),
    codigoempresa      varchar(5),
    entidad            varchar(100),
    tipo               varchar(3),
    linea_credito      numeric(18,2),
    linea_no_utilizada numeric(18,2),
    linea_utilizada    numeric(18,2),
    fecha_carga        timestamp(3) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS operador.moviles (
    periodo           varchar(6),
    documento         citext,
    ape_pat           varchar(100),
    ape_mat           varchar(100),
    prenombres        varchar(100),
    telefono          varchar(9),
    fecha_alta        date,
    plan_movil        varchar(100),
    modalidad         varchar(50),
    empresa_operadora varchar(60),
    fecha_carga       timestamp(3) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS operador.sueldos (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo                varchar(6) NOT NULL,
    tipodoc                varchar(10),
    documento              citext,
    apenom                 varchar(250),
    ruc                    varchar(20),
    empresa                varchar(250),
    genero                 varchar(20),
    sueldo                 numeric(18,2),
    gratif_bono            numeric(18,2),
    ingreso_estimado_anual numeric(18,2),
    cod_rango_sueldo       varchar(5),
    rango_sueldo           varchar(50),
    segmento_sueldo        varchar(50),
    nivel_ingreso          varchar(30),
    fecha_carga            timestamp(3) NOT NULL DEFAULT now()
);
